const Glyph* glyph(char ch) {
    for (const Glyph& glyph_entry : kGlyphs) {
        if (glyph_entry.ch == ch) {
            return &glyph_entry;
        }
    }
    if (ch >= 'a' && ch <= 'z') {
        const char upper = static_cast<char>(std::toupper(static_cast<unsigned char>(ch)));
        for (const Glyph& glyph_entry : kGlyphs) {
            if (glyph_entry.ch == upper) {
                return &glyph_entry;
            }
        }
    }
    return nullptr;
}
